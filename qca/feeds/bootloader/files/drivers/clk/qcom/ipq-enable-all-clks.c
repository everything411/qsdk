typedef struct {
	uint32_t mode_reg;      /* PLL_MODE register offset */
	uint8_t  l_val;         /* L value */
	uint64_t alpha_val;     /* Alpha value (0 if not used) */
	uint32_t config_ctl;    /* CONFIG_CTL value (0 if not used) */
} pll_config_entry_t;

