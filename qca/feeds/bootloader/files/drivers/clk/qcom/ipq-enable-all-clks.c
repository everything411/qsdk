/*
 * Helper function to configure a single RCGR from config entry
 */
int hermosa_gcc_configure_rcgr_entry(const rcgr_config_entry_t *entry)
{
	uint32_t cfg_val;
	uint32_t cmd_val;
	int timeout = 1000;

	/* Read current CMD and CFG register values */
	cmd_val = readl(entry->cmd_rcgr);
	cfg_val = readl(entry->cfg_rcgr);

	/* Clear the fields */
	cfg_val &= ~(RCGR_CFG_SRC_SEL_FMSK |
	             RCGR_CFG_SRC_DIV_FMSK |
	             CLOCK_CFG_RCGR_MODE_FMSK);

	/* Program the source and divider values */
	cfg_val |= (entry->src_sel << RCGR_CFG_SRC_SEL_SHIFT) & RCGR_CFG_SRC_SEL_FMSK;
	cfg_val |= ((entry->src_div - 1) << RCGR_CFG_SRC_DIV_SHIFT) & RCGR_CFG_SRC_DIV_FMSK;

	/* Set MND counter mode depending on if it is in use */
	if (entry->m_val != 0 && (entry->m_val < entry->n_val)) {
		if (entry->m_reg)
			writel(entry->m_val, entry->m_reg);
		if (entry->n_reg)
			writel(NOT_N_MINUS_M(entry->n_val, entry->m_val), entry->n_reg);
		if (entry->d_reg)
			writel(NOT_2D(entry->n_val), entry->d_reg);

		cfg_val |= ((CLOCK_CFG_CFG_DUAL_EDGE_MODE_VAL << CLOCK_CFG_RCGR_MODE_SHFT)
		            & CLOCK_CFG_RCGR_MODE_FMSK);
	}

	/* Write the final CFG register value */
	writel(cfg_val, entry->cfg_rcgr);

	/* Trigger update */
	cmd_val |= RCGR_CMD_UPDATE;
	cmd_val |= RCGR_CMD_ROOT_EN;
	writel(cmd_val, entry->cmd_rcgr);

	/* Wait for update to complete */
	while (timeout-- > 0) {
		cmd_val = readl(entry->cmd_rcgr);
		if (!(cmd_val & RCGR_CMD_UPDATE))
			return 0;
		udelay(1);
	}

	return -1;  /* Timeout */
}

void ipq_enable_all_clks(void)
{
	int ret;
	int timeout = 1000;
	uint32_t cbcr_val;
	uintptr_t cbcr_reg;
	const unsigned long *ena_vote_clocks;
	const unsigned long *cbcr_clocks;
	const rcgr_config_entry_t *rcgr_configs;
	size_t ena_vote_count, cbcr_count, rcgr_count;

#ifdef ENABLE_PLL_CONFIG
	/* Step 1: Enable all PLLs */
	ret = hermosa_gcc_enable_plls();
	if (ret != HERMOSA_GCC_SUCCESS)
		printf("PLL clock enable failed.\n");
#endif

	/* Select clock arrays based on target */
#if defined(CONFIG_TARGET_IPQ9650)
	ena_vote_clocks = ipq9650_ena_vote_clocks;
	ena_vote_count = ARRAY_SIZE(ipq9650_ena_vote_clocks);
	cbcr_clocks = ipq9650_all_cbcr_clocks;
	cbcr_count = ARRAY_SIZE(ipq9650_all_cbcr_clocks);
	rcgr_configs = ipq9650_rcgr_configs;
	rcgr_count = ARRAY_SIZE(ipq9650_rcgr_configs);
	printf("Configuring clocks for IPQ9650 (Juhu)\n");
#else /* CONFIG_TARGET_IPQ5210 */
	ena_vote_clocks = ipq5210_ena_vote_clocks;
	ena_vote_count = ARRAY_SIZE(ipq5210_ena_vote_clocks);
	cbcr_clocks = ipq5210_all_cbcr_clocks;
	cbcr_count = ARRAY_SIZE(ipq5210_all_cbcr_clocks);
	rcgr_configs = ipq5210_rcgr_configs;
	rcgr_count = ARRAY_SIZE(ipq5210_rcgr_configs);
	printf("Configuring clocks for IPQ5210\n");
#endif

	/* Enable vote clocks */
	for (size_t i = 0; i < ena_vote_count; i++)
		writel(0xFFFFFFFF, (void *)ena_vote_clocks[i]);

	/* Step 2: Configure all RCGRs */
	for (size_t i = 0; i < rcgr_count; i++) {
		pr_debug("enabling RCGR 0x%08lx\n", rcgr_configs[i].cmd_rcgr);
		ret = hermosa_gcc_configure_rcgr_entry(&rcgr_configs[i]);
		if (ret != 0) {
			printf("failed to enabled RCGR 0x%08lx\n", rcgr_configs[i].cmd_rcgr);
			/* Continue even if one fails */
			continue;
		}
	}

	/* Step 3: Enable all CBCRs */
	for (size_t i = 0; i < cbcr_count; i++) {

		cbcr_reg = cbcr_clocks[i];

		/* Check if already enabled */
		cbcr_val = readl(cbcr_reg);
		if (!(cbcr_val & CBCR_CLK_OFF)) {
			pr_debug("clock 0x%08lx already enabled\n", cbcr_reg);
			continue;
		}

		/* Enable the clock branch */
		cbcr_val |= CBCR_CLK_ENABLE;
		writel(cbcr_val, cbcr_reg);

                timeout = 10000;
		/* Wait for clock to turn on (CLK_OFF bit to clear) */
		while (timeout-- > 0) {
			cbcr_val = readl(cbcr_reg);
			if (!(cbcr_val & CBCR_CLK_OFF)) {
				pr_debug("clock 0x%08lx enabled\n", cbcr_reg);
				break;
			}
			udelay(1);
		}
		if (cbcr_val & CBCR_CLK_OFF)
			printf("clock 0x%08lx failed to enable\n", cbcr_reg);
	}
}
