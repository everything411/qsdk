/**
 * geni_se_read_proto() - Read the protocol configured for a serial engine
 * @se_base:		Base address of SE.
 *
 * Return: Protocol value as configured in the serial engine.
 */
static u32 geni_se_read_proto(phys_addr_t se_base)
{
	u32 val;

	val = readl(se_base + GENI_FW_REVISION_RO);

	return (val & FW_REV_PROTOCOL_MSK) >> FW_REV_PROTOCOL_SHFT;
}

void geni_se_reg_write(u32 *value, uint64_t offset, u32 len)
{
	int i;
	for (i = 0; i < len; i++)
		writel(value[i], (uintptr_t)(offset + (i * 4)));
}

static int qcom_geni_se_probe(struct udevice *dev)
{
	phys_addr_t se_base = dev_read_addr(dev);
	struct geni_se_cfg *cfg = (struct geni_se_cfg*)dev_get_driver_data(dev);

	/* Disable Peripheral clock and Output control */
	writel(0x0, se_base + SE_GENI_OUTPUT_CTRL_OFFSET);
	writel(0x378, se_base + SE_GENI_CGC_CTRL_OFFSET);
	writel(0x0, se_base + SE_GENI_CLK_CTRL_OFFSET);
	writel(0x78, se_base + SE_GENI_CGC_CTRL_OFFSET);

	/* Configure INIT_CFG revision */
	writel(cfg->revision->config_version,
			(se_base + SE_GENI_INIT_CFG_REVISION_OFFSET));

	/* CFG_REG_0_18 Programming */
	geni_se_reg_write(cfg->reg_0_18,
				(se_base + SE_GENI4_IMAGE_REG0_OFFSET),
				cfg->reg_0_18_len);

	/* CFG_REG_64_113 Programming */
	geni_se_reg_write(cfg->reg_64_113,
				(se_base + SE_GENI4_IMAGE_REG64_OFFSET),
				cfg->reg_64_113_len);

	/* If SE is not using mini-core, program CFG_RAMn region as well */
	if (!(readl(se_base + SE_HW_PARAM_2_OFFSET) &
			SE_GENI_USE_MINICORES_MASK)) {
		geni_se_reg_write(cfg->ram,
					(se_base + SE_GENI_CFG_RAMn_OFFSET),
					cfg->ram_len);
	}

	/* Enable Peripheral clock */
	writel(0x1, se_base + SE_GENI_FORCE_DEFAULT_REG_OFFSET);
	writel(0x378, se_base + SE_GENI_CGC_CTRL_OFFSET);
	writel(0x1, se_base + SE_GENI_CLK_CTRL_OFFSET);
	writel(0x78, se_base + SE_GENI_CGC_CTRL_OFFSET);

	/* Configure FW Revision and Protocol */
	writel((cfg->revision->serial_protocol << 8 |
		cfg->revision->firmware_version >> 8),
		se_base + SE_GENI_FW_REVISION_OFFSET);

	writel(cfg->revision->firmware_version & 0xFF,
			se_base + SE_GENI_S_FW_REVISION_OFFSET);

	/* Enable Output control */
	writel(0x7F, se_base + SE_GENI_OUTPUT_CTRL_OFFSET);

	/* Enable DMA for SPI SE alone */
	if (cfg->se_mode == GENI_SE_SPI)
		writel(0x1, se_base + SE_DMA_IF_EN_OFFSET);

	if (geni_se_read_proto(se_base) != cfg->se_mode)
		return -EPROTONOSUPPORT;

	return 0;
}

